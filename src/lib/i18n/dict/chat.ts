export type ChatKey = keyof typeof CHAT_T;

/** `t("kalit", { n: 5 })` — `{n}` kabi o'rinbosarlar almashtiriladi */
export function chatT(locale: Locale, key: ChatKey, vars?: Record<string, string | number>): string {
  let s: string = CHAT_T[key][locale];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
